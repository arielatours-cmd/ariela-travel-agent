"""QA for the PUBLIC_BASE_URL misconfiguration warning, per Shlomo's report
(20.10): the WhatsApp vacation link customers see was truncated ("ariela-
travel-agent.onrender" missing its ".com") because the Render environment's
own PUBLIC_BASE_URL variable was set without its TLD - a pure environment
misconfiguration, not a code bug (confirmed: the link is always built
deterministically from this one value via whatsapp_bridge._waiting_link,
never generated by the model). The business owner is fixing the Render
variable directly; this only adds an early, visible surface for the SAME
class of mistake happening again - a startup log warning plus a /health
field - so it's caught before the next deploy rather than rediscovered live
by a customer.

Run: python3 tools/qa_public_base_url_warning.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("ANTHROPIC_API_KEY", "test-key-not-real")

import config
import app as app_module

FAILED = []


def check(name, cond):
    status = "PASS" if cond else "FAIL"
    print(f"[{status}] {name}")
    if not cond:
        FAILED.append(name)


check("empty PUBLIC_BASE_URL (feature simply unused) -> no warning",
      config._public_base_url_warning("") is None)
check("a genuine, complete https URL with a real TLD -> no warning",
      config._public_base_url_warning("https://ariela-travel-agent.onrender.com") is None)
check("Shlomo's exact live repro: the host is missing its TLD entirely "
      "('.onrender' instead of '.onrender.com') -> a specific warning",
      config._public_base_url_warning("https://ariela-travel-agent.onrender") is not None)
check("a value with no scheme at all (not an absolute URL) -> a warning "
      "too, a different but still real misconfiguration",
      config._public_base_url_warning("ariela-travel-agent.onrender.com") is not None)
check("a trailing slash alone (already stripped by config.py before this "
      "check ever runs) still resolves fine once stripped",
      config._public_base_url_warning("https://ariela-travel-agent.onrender.com") is None)

with app_module.app.test_client() as client:
    resp = client.get("/health")
    body = resp.get_json()
    check("/health exposes public_base_url_warning (None in this test "
          "environment, since PUBLIC_BASE_URL is unset here)",
          "public_base_url_warning" in body)

if FAILED:
    print(f"\n{len(FAILED)} FAILED: {FAILED}")
    sys.exit(1)
print("\nALL PUBLIC-BASE-URL-WARNING TESTS PASSED")
